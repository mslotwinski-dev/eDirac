    <h3>Eksperymenty</h3>
    <Section>
      Oczywiście moment kiedy teoria jest tak doskonała, że wyprzedza praktykę
      jest w historii nauki rzadki. Zazwyczaj to eksperymenty prowadzą do
      odkryć, które następnie muszą być w jakiś sposób wytłumaczone. Bo to tym
      jest teoria w naukach empirycznymch — wytłumaczeniem dlaczego świat działa
      tak, a nie inaczej. Wyszukiwanie setek przykładów takich eksperymentów nie
      ma sensu, bo każde najprostsze zjawisko, jakie obserwujesz na co dzień
      jest zbadane poprzez jakiś eksperyment, który ktoś kiedyś wykonał.
    </Section>
